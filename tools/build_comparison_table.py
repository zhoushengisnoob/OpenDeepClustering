"""Generate the configuration-matched method comparison from committed records.

Methods are grouped by a protocol key built from the facts that make two runs
comparable: dataset digests, sample and feature counts, preprocessing recipe,
and metric definitions. Methods sharing a key appear in one table and may be
read against each other. Methods with different keys appear in separate
tables and must not be.

Nothing here reads the GPU server. Every value comes from the per-seed metrics
in docs/benchmarks/records/, so the table regenerates anywhere the repository
is checked out.

    python tools/build_comparison_table.py --check
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import statistics as st
import sys
from pathlib import Path

RECORDS_DIR = Path("docs/benchmarks/records")
OUTPUT = Path("docs/benchmarks/comparison.md")
METRICS = ("acc", "nmi", "ari")

T_CRITICAL_95 = {
    1: 12.706, 2: 4.303, 3: 3.182, 4: 2.776, 5: 2.571, 6: 2.447, 7: 2.365,
    8: 2.306, 9: 2.262, 10: 2.228, 11: 2.201, 12: 2.179, 13: 2.160, 14: 2.145,
    15: 2.131, 16: 2.120, 17: 2.110, 18: 2.101, 19: 2.093, 20: 2.086,
}

# Evidence status per estimator, mirroring docs/algorithms.md.
STATUS = {
    "AutoencoderKMeans": "Architecture reference",
    "VaDE": "Validated with stated instability",
    "DeepCluster": "Unresolved: known defect",
    "DEC": "Reference implementation",
    "IDEC": "Reference implementation",
}

# Caveats that must travel with a figure rather than sit in prose elsewhere.
CAVEATS = {
    "VaDE": (
        "Seed range 0.149 in ACC. Quote with seed count and interval; see the "
        "[variance record](vade-variance-2026-10-29.md)."
    ),
    "DeepCluster": (
        "**Below raw-pixel KMeans (0.5342).** Embedding collapses at "
        "initialisation; see the [collapse record](deepcluster-collapse-2026-10-28.md)."
    ),
}

CONFIG_LINK = (
    "https://github.com/zhoushengisnoob/OpenDeepClustering/blob/master/"
    "configs/benchmarks/{name}"
)
CONFIG_FILE = {
    "AutoencoderKMeans": "autoencoder_kmeans_mnist_reference.yaml",
    "VaDE": "vade_mnist_reference.yaml",
    "DeepCluster": "deepcluster_mnist_reference.yaml",
    "DEC": "dec_mnist_reference.yaml",
    "IDEC": "idec_mnist_reference.yaml",
}


def interval(values: list[float]) -> tuple[float, float, float]:
    """Return mean, sample standard deviation and 95% CI half-width."""
    mean = st.mean(values)
    sample_sd = st.stdev(values) if len(values) > 1 else 0.0
    half = (
        T_CRITICAL_95.get(len(values) - 1, 1.96) * sample_sd / math.sqrt(len(values))
        if len(values) > 1 else 0.0
    )
    return mean, sample_sd, half


def protocol_key(block: dict) -> tuple:
    """The facts that decide whether two runs may be compared at all."""
    dataset = block["dataset"]
    config = dataset["config"]
    return (
        config.get("kind"),
        dataset["samples"],
        dataset["features"],
        config.get("split"),
        config.get("normalization"),
        bool(config.get("flatten", True)),
        dataset["features_sha256"],
        dataset["labels_sha256"],
    )


def describe_key(key: tuple) -> list[str]:
    kind, samples, features, split, normalization, flatten, features_sha, labels_sha = key
    return [
        f"- Dataset: `{kind}`, split `{split}`, {samples:,} samples x {features} features",
        f"- Preprocessing: normalization `{normalization}`, "
        f"flattened to 2D: {'yes' if flatten else 'no (NCHW retained)'}",
        f"- Feature digest after preprocessing: `{features_sha}`",
        f"- Label digest: `{labels_sha}`",
    ]


def load_records() -> list[tuple[str, dict, Path]]:
    entries = []
    for path in sorted(RECORDS_DIR.glob("*.json")):
        manifest = json.loads(path.read_text(encoding="utf-8"))
        for estimator, block in manifest["estimators"].items():
            entries.append((estimator, block, path))
    return entries


def render() -> str:
    entries = load_records()
    groups: dict[tuple, list] = {}
    for estimator, block, path in entries:
        groups.setdefault(protocol_key(block), []).append((estimator, block, path))

    # Largest group first so the most comparable set leads.
    ordered = sorted(groups.items(), key=lambda item: (-len(item[1]), str(item[0])))

    lines = [
        "# Method comparison",
        "",
        "Generated by `tools/build_comparison_table.py` from the per-seed records "
        "in [`records/`](records/). Every figure regenerates from a committed file; "
        "no GPU or server access is needed.",
        "",
        "```bash",
        "python tools/build_comparison_table.py --check",
        "```",
        "",
        "Methods are grouped by **protocol key**: dataset identity and digests, "
        "sample and feature counts, split, and preprocessing. Methods inside one "
        "group ran on byte-identical inputs and may be read against each other. "
        "**Methods in different groups must not be compared** — a difference "
        "between them mixes method and protocol.",
        "",
        "Deviations are sample standard deviations; intervals are two-sided 95% "
        "Student-t confidence intervals for the mean. None of these figures is a "
        "reproduction of a published result; see each method's specification for "
        "the paper-fidelity boundary.",
        "",
    ]

    for index, (key, members) in enumerate(ordered, start=1):
        members.sort(key=lambda item: -item[1]["aggregates"]["acc"]["mean"])
        lines.append(f"## Protocol group {index}")
        lines.append("")
        lines.extend(describe_key(key))
        commits = sorted({block["git_sha"] for _, block, _ in members})
        lines.append(
            "- Commit"
            + ("s" if len(commits) > 1 else "")
            + ": "
            + ", ".join(f"`{sha[:12]}`" for sha in commits)
        )
        environments = sorted(
            {
                f"torch {block['environment']['torch']}, "
                f"python {block['environment']['python']}"
                for _, block, _ in members
            }
        )
        lines.append("- Environment: " + "; ".join(environments))
        lines.append("")
        lines.append(
            "| Estimator | Status | Seeds | ACC | ACC 95% CI | NMI | ARI | Stop | Config | Record |"
        )
        lines.append("| --- | --- | ---: | ---: | :---: | ---: | ---: | --- | --- | --- |")
        for estimator, block, path in members:
            per_seed = block["per_seed"]
            cells = {}
            for metric in METRICS:
                values = [entry["metrics"][metric] for entry in per_seed]
                mean, sd, half = interval(values)
                cells[metric] = (mean, sd, half)
            stop = ", ".join(
                f"{reason} ({count})" if count != len(per_seed) else reason
                for reason, count in sorted(block["stop_reasons"].items())
            )
            config_name = CONFIG_FILE.get(estimator, "")
            config_cell = (
                f"[`{config_name}`]({CONFIG_LINK.format(name=config_name)})"
                if config_name else "—"
            )
            acc_mean, acc_sd, acc_half = cells["acc"]
            lines.append(
                "| `%s` | %s | %d | %.4f ± %.4f | [%.4f, %.4f] | %.4f ± %.4f | "
                "%.4f ± %.4f | %s | %s | [%s](records/%s) |" % (
                    estimator, STATUS.get(estimator, "—"), len(per_seed),
                    acc_mean, acc_sd, acc_mean - acc_half, acc_mean + acc_half,
                    cells["nmi"][0], cells["nmi"][1],
                    cells["ari"][0], cells["ari"][1],
                    stop, config_cell, path.stem, path.name,
                )
            )
        lines.append("")
        notes = [
            (estimator, CAVEATS[estimator])
            for estimator, _, _ in members if estimator in CAVEATS
        ]
        if notes:
            for estimator, note in notes:
                lines.append(f"- `{estimator}`: {note}")
            lines.append("")

    if len(ordered) > 1:
        lines.append("## Why the groups are separate")
        lines.append("")
        lines.append(
            "The groups above differ in preprocessing, so their feature digests "
            "differ and their numbers are not on a common scale. DEC and IDEC use "
            "the per-sample DEC normalization their papers specify; the "
            "multi-stage, iterative and generative representatives use unit "
            "scaling. Placing all five in one ranking would attribute a "
            "preprocessing difference to the methods."
        )
        lines.append("")

    lines.append("## Reference points")
    lines.append("")
    lines.append(
        "On the unit-scaled 70,000-sample MNIST matrix, KMeans applied directly "
        "to the raw 784 pixel features reaches 0.5342 ACC and 0.4807 NMI. A "
        "representation learner scoring below that line is not contributing, "
        "which is the basis for `DeepCluster`'s status."
    )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check", action="store_true",
        help="Fail if the committed table differs from a fresh generation.",
    )
    args = parser.parse_args()

    rendered = render()
    digest = hashlib.sha256(rendered.encode()).hexdigest()

    if args.check:
        if not OUTPUT.exists():
            print(f"FAILED: {OUTPUT} does not exist; run without --check first.")
            return 1
        current = OUTPUT.read_text(encoding="utf-8")
        if current != rendered:
            print(
                f"FAILED: {OUTPUT} is stale. Regenerate with:\n"
                "  python tools/build_comparison_table.py"
            )
            return 1
        print(f"{OUTPUT} matches the records (sha256 {digest[:16]}).")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"Wrote {OUTPUT} ({len(rendered)} bytes, sha256 {digest[:16]}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
